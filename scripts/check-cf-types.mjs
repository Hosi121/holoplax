import { spawnSync } from "node:child_process";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

const scratch = await mkdtemp(join(tmpdir(), "holoplax-types-"));
try {
  const file = join(scratch, "env.d.ts");
  const result = spawnSync(
    process.execPath,
    [
      "node_modules/wrangler/bin/wrangler.js",
      "types",
      file,
      "--include-runtime",
      "false",
      "--strict-vars",
      "false",
    ],
    { stdio: "pipe", encoding: "utf8" },
  );
  if (result.status !== 0) throw new Error(result.stderr || result.stdout);
  const normalize = (source) =>
    source
      .replace(/^\/\/ Generated by Wrangler.*$/m, "")
      .replace(/mainModule: typeof import\("[^"]*"\)/, 'mainModule: typeof import("WORKER")');
  if (
    normalize(await readFile(file, "utf8")) !==
    normalize(await readFile("worker-configuration.d.ts", "utf8"))
  ) {
    throw new Error(
      "Worker bindings have changed. Run npm run cf:types and commit the generated file.",
    );
  }
  console.log("Worker binding types are current.");
} finally {
  await rm(scratch, { recursive: true, force: true });
}
